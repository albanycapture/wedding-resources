// Builds index.html from the files in src/.
//   node build.mjs                 -> writes index.html (open it in any browser)
//   node build.mjs --page <path>   -> also writes the bare page (no <html> wrapper) for publishing
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const src = name => readFileSync(join(here, 'src', name), 'utf8');
const scripts = readdirSync(join(here, 'src')).filter(f => f.endsWith('.js')).sort();

const page =
  src('05-top.html') +
  '<style>\n' + src('10-style.css') + '</style>\n' +
  src('20-shell.html') +
  "<script>\n(() => {\n'use strict';\n" + scripts.map(src).join('\n') + '\n})();\n</script>\n';

if (page.split('</script>').length !== 2) throw new Error('A source file contains a closing script tag.');

const html =
  '<!doctype html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n' +
  '<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">\n' +
  '<style>:root{color-scheme:light;padding:env(safe-area-inset-top,0px) 0 env(safe-area-inset-bottom,0px)}body{margin:0;font:14px system-ui,sans-serif}img{max-width:100%}[hidden]{display:none!important}</style>\n' +
  '</head>\n<body>\n' +
  '<!-- Frame Sense. Generated by build.mjs from the files in src/. Edit those, then run: node build.mjs -->\n' +
  page + '</body>\n</html>\n';

writeFileSync(join(here, 'index.html'), html);
const i = process.argv.indexOf('--page');
if (i > 0 && process.argv[i + 1]) writeFileSync(process.argv[i + 1], page);
console.log(`index.html  ${(html.length / 1024).toFixed(0)} KB  from ${scripts.length} scripts`);
