// Builds index.html from the files in src/.
//   node build.mjs                 -> writes index.html (open it in any browser)
//   node build.mjs --page <path>   -> also writes the bare page (no <html> wrapper) for publishing
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const src = name => readFileSync(join(here, 'src', name), 'utf8');
const scripts = readdirSync(join(here, 'src')).filter(f => f.endsWith('.js')).sort();

const body =
  '<style>\n' + src('10-style.css') + '</style>\n' +
  src('20-shell.html') +
  "<script>\n(() => {\n'use strict';\n" + scripts.map(src).join('\n') + '\n})();\n</script>\n';
if (body.split('</script>').length !== 2) throw new Error('A source file contains a closing script tag.');

/* The published page loads its two typefaces from Google Fonts. index.html carries them inside
   the file instead, so a local copy makes no network requests at all and works with no internet. */
const LATIN = 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD';
const face = (family, file, axes) =>
  `@font-face{font-family:'${family}';font-style:normal;font-display:swap;${axes}` +
  `src:url(data:font/woff2;base64,${readFileSync(join(here, 'src', 'fonts', file)).toString('base64')}) format('woff2');unicode-range:${LATIN}}`;
const embeddedFonts =
  '<style>\n/* Typefaces: Archivo and Chivo Mono by Omnibus-Type, SIL Open Font License 1.1 (openfontlicense.org). */\n' +
  face('Archivo', 'archivo-latin.woff2', 'font-weight:100 900;font-stretch:62% 125%;') + '\n' +
  face('Chivo Mono', 'chivo-mono-latin.woff2', 'font-weight:400 600;') + '\n</style>\n';
const top = src('05-top.html');
const topLocal = top.replace(/<link rel="stylesheet" href="https:\/\/fonts\.googleapis\.com[^>]*>\n?/, embeddedFonts);
if (topLocal === top) throw new Error('The Google Fonts link was not found in 05-top.html.');

const page = top + body;
const local = topLocal + body;

const html =
  '<!doctype html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n' +
  '<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">\n' +
  '<style>:root{color-scheme:light;padding:env(safe-area-inset-top,0px) 0 env(safe-area-inset-bottom,0px)}body{margin:0;font:14px system-ui,sans-serif}img{max-width:100%}[hidden]{display:none!important}</style>\n' +
  '</head>\n<body>\n' +
  '<!-- Frame Sense. Generated by build.mjs from the files in src/. Edit those, then run: node build.mjs -->\n' +
  local + '</body>\n</html>\n';
if (/https?:\/\/(?!www\.w3\.org)/.test(local.replace(/openfontlicense\.org/g, ''))) throw new Error('index.html still points at an outside address.');

writeFileSync(join(here, 'index.html'), html);
const i = process.argv.indexOf('--page');
if (i > 0 && process.argv[i + 1]) writeFileSync(process.argv[i + 1], page);
console.log(`index.html  ${(html.length / 1024).toFixed(0)} KB  from ${scripts.length} scripts`);
